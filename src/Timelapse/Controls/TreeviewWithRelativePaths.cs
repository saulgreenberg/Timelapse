    // TreeViewWithRelativePaths is an extended treeview control designed to display relative paths as collected from the current image set.
    // It is used twice in Timelapse:
    // - Select | All files in a folder and its subfolders... , where the pull-right menu is displayed as a treeViewWithRelativePaths
    // - Select | Custom selection...  RelativePath folder, where the combobox (actually a dropdown button) displays the treeViewWithRelativePaths
    public class TreeViewWithRelativePaths : TreeView
    {
        #region Public properties
        // The tree's single, permanent root item (see SetTreeViewContentsToRelativePathList) - it
        // represents "no folder filter, show everything" and is always present and always expanded,
        // even when there are no real folders at all. Its own Path/Name is this sentinel rather than
        // a real relative path, so consumers can tell "the active selection is 'all files'" apart
        // from "the active selection is a stale/unset value" - compare SelectedPath against this
        // instead of leaving SelectedPath blank for that case.
        public const string AllFilesPath = "All";

        // The currently selected path (e.g., a/b/c, or AllFilesPath)
        public string SelectedPath { get; set; }
        // Whether or not to invoke some code
        // Used to stop unecessary invocation of the SelectedItemChanged callback, which can otherwise lead to performance issues
        public bool DontInvoke { get; set; }

        // Whether or not to apply the focus on the selected item
        public bool FocusSelection { get; set; } = true;

        // Raised only when SelectAndHighlightPathItem treats a SelectedItemChanged firing as a
        // genuine user pick of a different folder (i.e. it updated SelectedPath) - as opposed to
        // WPF's own TreeView.HandleSelectionAndCollapsed reselecting a collapsed ancestor when the
        // real active item becomes hidden, which also fires SelectedItemChanged but is deliberately
        // NOT treated as a pick (see SelectAndHighlightPathItem's prefix check). Consumers with side
        // effects beyond this control's own highlighting - e.g. Custom Selection closing its dropdown,
        // or changing the active file selection - should react to this event rather than the raw
        // SelectedItemChanged, so collapsing/expanding a branch near the active item doesn't trigger
        // them.
        public event EventHandler ActivePathSelected;

        // True only if there's at least one real folder beneath the permanent "All" root - ItemList
        // itself is never empty once populated (it always contains at least the "All" item), so this
        // checks All's own children rather than ItemList's count.
        public bool HasContent => this.ItemList is [PathItem allItem] && allItem.Items.Count > 0;
        #endregion

        #region Private properties
        private ItemProvider ItemProvider { get; set; }
        private List<Item> ItemList { get; set; }
        #endregion

        #region Constructor
        public TreeViewWithRelativePaths()
        {
            this.SelectedItemChanged += TreeView_SelectedItemChanged;
            this.Loaded += TreeView_OnLoaded;

            // WPF's TreeView virtualizes item containers by default: a TreeViewItem whose container
            // has never been scrolled into view doesn't exist yet, even if its parent is expanded and
            // UpdateLayout() has run - ItemContainerGenerator.ContainerFromItem returns null for it.
            // ExpandAllRecursive, CollapseAllRecursive, and ExpandAll's final BringIntoView lookup all
            // walk the tree via ContainerFromItem, so without this they silently stop at (or can't
            // find) any node that hasn't already been scrolled into view at least once. This matters
            // for the top-level items panel; nested per-node panels generated by the
            // HierarchicalDataTemplate don't appear to virtualize regardless of this setting (measured
            // empirically - no difference with it on or off), so it's kept for top-level reliability
            // without being the thing that controls whether the whole tree gets eagerly realized.
            // Nothing defaults to expanded any more (see ExpandToActivePathOnly), so in normal use only
            // a small number of containers (the active path) ever need to exist regardless of this
            // setting - full realization only happens when the user explicitly clicks "Expand all".
            VirtualizingPanel.SetIsVirtualizing(this, false);

            // When the user manually collapses a node (via its own arrow) that contains the currently
            // selected/active item, WPF's TreeView.HandleSelectionAndCollapsed moves selection up to the
            // collapsed node itself (an item can't stay "selected" while hidden) and re-fires
            // SelectedItemChanged synchronously, from inside the same IsExpanded property-changed
            // callback that triggers it - before the bubbling Collapsed routed event reaches any
            // handler, so that event can't be used to intercept this. SelectAndHighlightPathItem's own
            // prefix check guards against it instead - see its comment.
            //
            // Once a node is later re-expanded, the active item's container becomes visible again but
            // stays deselected (WPF cleared its IsSelected when moving selection to the ancestor above),
            // so nothing re-highlights it on its own - RestoreActiveItemHighlightAndScroll, run on every
            // Expanded event, does that.
            this.AddHandler(TreeViewItem.ExpandedEvent, new RoutedEventHandler(OnAnyTreeViewItemExpanded), true);

            // "All" (see AllFilesPath) is the tree's permanent root and has no meaningful collapsed
            // state - CollapseAll/ExpandAll both keep it expanded, but the user could otherwise
            // collapse it directly via its own arrow or the Left-arrow key. That must be blocked
            // pre-emptively, not undone afterward (e.g. via the Collapsed event): collapsing it while
            // a real folder is active would hide that folder too, and WPF's
            // TreeView.HandleSelectionAndCollapsed moves selection up to "All" and fires
            // SelectedItemChanged synchronously, from inside the same IsExpanded property-changed
            // callback that collapsing triggers - before any Collapsed handler gets a chance to run.
            // That reselection is indistinguishable from a deliberate click on All's own label, which
            // must still work (it's the whole point of AllFilesPath), so nothing downstream can
            // safely tell the two apart once the collapse has actually happened - the only reliable
            // fix is making sure it never does.
            this.PreviewMouseLeftButtonDown += TreeViewWithRelativePaths_PreventAllRootCollapseOnClick;
            this.PreviewKeyDown += TreeViewWithRelativePaths_PreventAllRootCollapseOnKey;
        }

        private void TreeViewWithRelativePaths_PreventAllRootCollapseOnClick(object sender, MouseButtonEventArgs e)
        {
            if (e.OriginalSource is DependencyObject source && IsAllRootToggleArrow(source))
            {
                e.Handled = true;
            }
        }

        private void TreeViewWithRelativePaths_PreventAllRootCollapseOnKey(object sender, KeyEventArgs e)
        {
            if (e.Key == Key.Left && e.OriginalSource is TreeViewItem { IsExpanded: true, DataContext: PathItem { Path: AllFilesPath } })
            {
                e.Handled = true;
            }
        }

        // Walks up from the click's original source looking for a ToggleButton (the expand/collapse
        // arrow in TreeViewItem's default template) before reaching the TreeViewItem itself, then
        // checks whether that TreeViewItem is specifically All's own (as opposed to some other item's
        // arrow, which must keep working normally).
        private static bool IsAllRootToggleArrow(DependencyObject source)
        {
            DependencyObject current = source;
            bool passedThroughToggleButton = false;
            while (current != null && current is not TreeViewItem)
            {
                if (current is ToggleButton)
                {
                    passedThroughToggleButton = true;
                }
                current = VisualTreeHelper.GetParent(current);
            }
            return passedThroughToggleButton && current is TreeViewItem { DataContext: PathItem { Path: AllFilesPath } };
        }

        private void OnAnyTreeViewItemExpanded(object sender, RoutedEventArgs e)
        {
            // DontInvoke is set by callers (TreeView_OnLoaded, ExpandAll) that are already doing their
            // own controlled expand-and-highlight sequence; skip so this doesn't run redundantly (or
            // interfere) mid-sequence. ExpandAll calls RestoreActiveItemHighlightAndScroll explicitly
            // itself once its own bulk expand is done and DontInvoke is back to false.
            if (this.DontInvoke)
            {
                return;
            }
            RestoreActiveItemHighlightAndScroll();
        }

        // Re-applies selection/focus to the active item (SelectedPath) if its container exists but
        // isn't currently selected - i.e. it just became reachable again (e.g. its parent was just
        // expanded) after WPF moved selection elsewhere while it was hidden - and scrolls it into
        // view. By default, both are skipped if the container already correctly shows as selected,
        // so this doesn't steal focus or scroll during unrelated expands elsewhere in the tree (e.g.
        // the user manually expanding some other, unrelated branch while the active item - already
        // selected and already visible - stays put). forceScroll overrides only the scrolling part
        // of that skip, for callers like ExpandAll where the active item's own position on screen can
        // change (e.g. it gets pushed down by everything newly expanded above it) even though its
        // selection state never did, since expanding doesn't itself change what's selected.
        private void RestoreActiveItemHighlightAndScroll(bool forceScroll = false)
        {
            if (string.IsNullOrWhiteSpace(this.SelectedPath))
            {
                return;
            }
            TreeViewItem selectedContainer = FindContainerForPath(this.SelectedPath);
            if (selectedContainer == null)
            {
                return;
            }
            if (selectedContainer.IsSelected && !forceScroll)
            {
                return;
            }
            if (!selectedContainer.IsSelected)
            {
                this.DontInvoke = true;
                if (this.FocusSelection)
                {
                    selectedContainer.IsSelected = true;
                    selectedContainer.Focus();
                }
                this.DontInvoke = false;
            }

            // Plain BringIntoView() scrolls the minimum distance needed to bring the item's bounding
            // box into the viewport, which can leave it sitting flush against the viewport edge (only
            // its top edge visible, as reported). Requesting a target rectangle padded above and below
            // the item's own bounds forces some margin into that scroll instead.
            selectedContainer.UpdateLayout();
            const double verticalMargin = 40;
            Rect paddedBounds = new(0, -verticalMargin, selectedContainer.ActualWidth, selectedContainer.ActualHeight + (2 * verticalMargin));
            selectedContainer.BringIntoView(paddedBounds);
        }
        #endregion

        #region Public methods
        // Wraps the real folders in a single permanent "All" root item (see AllFilesPath) rather than
        // listing them as multiple top-level items, so there's always exactly one item at the tree's
        // own top level - the active selection (a real folder, or AllFilesPath itself) is then always
        // reachable as a container somewhere beneath it, instead of "no folder active" being an
        // unrepresented, easily-stale special case (a blank/leftover SelectedPath with no
        // corresponding tree node).
        internal List<Item> SetTreeViewContentsToRelativePathList(List<string> relativePaths)
        {
            this.ItemProvider = new(relativePaths);
            PathItem allItem = new() { Name = AllFilesPath, Path = AllFilesPath, Items = ItemProvider.GetItems() };
            this.ItemList = [allItem];
            DataContext = this.ItemList;
            return this.ItemList;
        }
        #endregion

        #region Callbacks
        // This is triggered whenever the treeview is created, even though it may not yet be displayed
        private void TreeView_OnLoaded(object sender, RoutedEventArgs e)
        {
            ExpandToActivePathOnly();
        }

        // Re-expands just the path down to the active item (collapsing everything else first) -
        // nothing else defaults to expanded any more (see the removed ItemContainerStyle IsExpanded
        // setter in TimelapseWindow.xaml), since at thousands of entries that meant fully rendering
        // every single row just to populate the control. Called from the true initial Loaded event and
        // from OnItemsSourceChanged below (Loaded only fires once per attachment to the visual tree -
        // it does NOT re-fire when a menu/dropdown with an already-constructed TreeViewWithRelativePaths
        // instance reopens and its ItemsSource is simply reassigned, which would otherwise leave the
        // reopened tree with nothing expanded or highlighted at all), and public so it can also be
        // invoked directly from an "Expand active" button as a fast, bounded alternative to ExpandAll
        // for large trees.
        public void ExpandToActivePathOnly()
        {
            if (string.IsNullOrWhiteSpace(this.SelectedPath))
            {
                return;
            }

            this.UnselectAll();
            this.CollapseAll();
            this.DontInvoke = true;
            ExpandAndShowPathDirectly(this.SelectedPath);
            this.DontInvoke = false;
        }

        // Finds the "All" root item's own container and children (see AllFilesPath/
        // SetTreeViewContentsToRelativePathList) - every path walk below starts here instead of at
        // this.ItemList directly, since "All" (not a real folder) is now the tree's only true
        // top-level item. Read-only: does not expand/collapse anything - by design "All" always
        // stays expanded (CollapseAll/ExpandAll both guarantee it), so a null result here means the
        // tree hasn't been populated yet rather than that "All" needs expanding first.
        private (TreeViewItem Container, List<Item> Children) TryGetAllRootContainerAndChildren()
        {
            if (this.ItemList is not [PathItem allItem])
            {
                return (null, null);
            }
            return this.ItemContainerGenerator.ContainerFromItem(allItem) is TreeViewItem allContainer
                ? (allContainer, allItem.Items)
                : (null, null);
        }

        // Expands and selects the given path by walking directly down its known segments - at each
        // level, finding and expanding only the one child matching the next segment, by name, via
        // the data model (this.ItemList / PathItem.Items), rather than ShowSelectedPathItem's old
        // approach of exhaustively expanding, fully realizing, searching, and then re-collapsing
        // every sibling at each level until the right one is found by luck of iteration order. That
        // brute-force approach silently realized the entire tree in the worst case (observed ~2
        // seconds for 6000+ entries) even though it only intended to expand one path - it only ever
        // looked cheap because the old blanket IsExpanded="True" style default meant everything was
        // already realized by the time this ran, so there was nothing left for it to do.
        private void ExpandAndShowPathDirectly(string path)
        {
            if (string.IsNullOrWhiteSpace(path))
            {
                return;
            }
            (TreeViewItem allContainer, List<Item> allChildren) = TryGetAllRootContainerAndChildren();
            if (allContainer == null)
            {
                return;
            }
            allContainer.IsExpanded = true;
            allContainer.UpdateLayout();

            TreeViewItem currentContainer = allContainer;
            if (path != AllFilesPath)
            {
                currentContainer = null;
                ItemsControl currentParent = allContainer;
                List<Item> currentLevelItems = allChildren;
                foreach (string pathSegment in path.Split('\\'))
                {
                    if (currentLevelItems == null)
                    {
                        return;
                    }
                    Item matchingChild = null;
                    foreach (Item candidate in currentLevelItems)
                    {
                        if (candidate.Name == pathSegment)
                        {
                            matchingChild = candidate;
                            break;
                        }
                    }
                    if (matchingChild == null)
                    {
                        return;
                    }
                    currentContainer = currentParent.ItemContainerGenerator.ContainerFromItem(matchingChild) as TreeViewItem;
                    if (currentContainer == null)
                    {
                        return;
                    }
                    currentContainer.IsExpanded = true;
                    // Force just this level's children to realize before the next iteration needs to
                    // look them up - the same progressive, level-by-level realization
                    // ShowSelectedPathItem used, just without the exhaustive sibling search around it.
                    currentContainer.UpdateLayout();
                    currentParent = currentContainer;
                    currentLevelItems = (matchingChild as PathItem)?.Items;
                }
                if (currentContainer == null)
                {
                    return;
                }
            }

            if (this.FocusSelection)
            {
                // Focusing this changes the highlight color to blue rather than shaded grey.
                currentContainer.IsSelected = true;
                currentContainer.Focus();
            }
            else
            {
                currentContainer.IsSelected = false;
            }
            currentContainer.BringIntoView();
        }

        // Unlike Loaded, this fires every time ItemsSource is (re)assigned - including on a reopen
        // that reuses an already-built data source. This callback runs synchronously the moment
        // ItemsSource changes, before WPF has generated even the top-level containers
        // ExpandAndShowPathDirectly needs to start its search - unlike Loaded, which only fires after
        // the element has already been through a layout pass. Forcing that pass here with an immediate
        // UpdateLayout() call (tried first) is NOT equivalent to Loaded's timing: called this early,
        // with nothing expanded yet to bound it, it forces WPF to eagerly realize every container in
        // the entire tree (confirmed empirically - identical cost whether VirtualizingPanel.IsVirtualizing
        // is on or off, meaning nested HierarchicalDataTemplate levels don't virtualize regardless).
        // Deferring via BeginInvoke(Loaded) instead lets WPF's own normal layout cycle run first -
        // which, now that nothing defaults to expanded, only needs to realize the small number of
        // top-level containers - before ExpandToActivePathOnly does its own targeted, level-by-level
        // expansion down to just the active item.
        protected override void OnItemsSourceChanged(System.Collections.IEnumerable oldValue, System.Collections.IEnumerable newValue)
        {
            base.OnItemsSourceChanged(oldValue, newValue);
            if (newValue == null)
            {
                return;
            }
            this.Dispatcher.BeginInvoke(DispatcherPriority.Loaded, new Action(ExpandToActivePathOnly));
        }

        // Highlight the selected item
        private void TreeView_SelectedItemChanged(object sender, RoutedPropertyChangedEventArgs<object> e)
        {
            if (false == this.DontInvoke && e.NewValue is PathItem pathItem)
            {
                this.SelectAndHighlightPathItem(pathItem);
            }
        }
        #endregion

        #region Private Search for Path, Select and Show Item
        // Select and highlight the pathItem if its not already selected
        private void SelectAndHighlightPathItem(PathItem pathItem)
        {
            if (null != pathItem && false == string.IsNullOrWhiteSpace(pathItem.Path))
            {
                if (this.SelectedPath == pathItem.Path)
                {
                    // Its already selected and thus highlit, so abort
                    return;
                }

                // If pathItem is an ANCESTOR of the path we already consider active (i.e. a prefix of
                // it), this SelectedItemChanged firing is almost certainly WPF's own
                // TreeView.HandleSelectionAndCollapsed moving selection up because the real active
                // item - a descendant - just got hidden by a manual collapse of pathItem, not a
                // genuine new selection. Don't let that overwrite SelectedPath with the shallower
                // path, or the original deep selection is permanently lost once re-expanded. (Trade-
                // off: a deliberate click directly on the ancestor's own label, right after a deeper
                // item was active, is indistinguishable from this and will also be ignored here - an
                // acceptable rare edge case against silently losing the real selection on every
                // manual collapse.)
                if (!string.IsNullOrWhiteSpace(this.SelectedPath) &&
                    this.SelectedPath.StartsWith(pathItem.Path + "\\", StringComparison.Ordinal))
                {
                    return;
                }

                this.SelectedPath = pathItem.Path;
                if (this.ItemContainerGenerator.ContainerFromItem(pathItem) is TreeViewItem tvi)
                {
                    tvi.IsSelected = true;
                    tvi.BringIntoView();
                }
                this.ActivePathSelected?.Invoke(this, EventArgs.Empty);
            }
        }

        #endregion

        #region Expand
        public void ExpandAll()
        {
            this.DontInvoke = true;
            foreach (var item in this.Items)
            {
                if (this.ItemContainerGenerator.ContainerFromItem(item) is TreeViewItem treeViewItem)
                {
                    ExpandAllRecursive(treeViewItem);
                }
            }
            this.DontInvoke = false;

            // Expanding ancestor folders above the active item can push it out of the visible scroll
            // area even though it was - and still is - already selected throughout (expanding a node
            // doesn't itself change what's selected), so forceScroll is needed here: the default
            // skip-if-already-selected behavior exists to avoid scrolling to the active item on an
            // unrelated expand elsewhere in the tree, but a full ExpandAll is exactly the case where
            // the active item's own on-screen position can change regardless.
            RestoreActiveItemHighlightAndScroll(forceScroll: true);
        }

        // Finds the TreeViewItem container currently hosting the given path, by walking down the
        // same known path segments ExpandAndShowPathDirectly/ItemProvider.Search use to find the
        // data item - at each level, querying only that level's own ItemContainerGenerator for the
        // one specific child matching the next segment, never scanning unrelated siblings or
        // descending into unrelated branches. O(depth), not O(tree size): a blind recursive search
        // over every realized container (the previous implementation) is O(n) per call, and since
        // this runs once per Expanded event during bulk tree realization, that made restoring the
        // highlight after a large (6000+ node) tree is rebuilt - e.g. the Select menu's submenu
        // reopening - an O(n^2) operation, observed taking several seconds. Read-only: does not
        // expand/collapse anything - callers must have already ensured the relevant containers are
        // realized (e.g. by expanding ancestors first).
        private TreeViewItem FindContainerForPath(string path)
        {
            if (string.IsNullOrWhiteSpace(path))
            {
                return null;
            }
            (TreeViewItem allContainer, List<Item> allChildren) = TryGetAllRootContainerAndChildren();
            if (allContainer == null)
            {
                return null;
            }
            if (path == AllFilesPath)
            {
                return allContainer;
            }

            ItemsControl currentParent = allContainer;
            List<Item> currentLevelItems = allChildren;
            TreeViewItem currentContainer = null;
            foreach (string pathSegment in path.Split('\\'))
            {
                if (currentLevelItems == null)
                {
                    return null;
                }
                Item matchingChild = null;
                foreach (Item candidate in currentLevelItems)
                {
                    if (candidate.Name == pathSegment)
                    {
                        matchingChild = candidate;
                        break;
                    }
                }
                if (matchingChild == null)
                {
                    return null;
                }
                currentContainer = currentParent.ItemContainerGenerator.ContainerFromItem(matchingChild) as TreeViewItem;
                if (currentContainer == null)
                {
                    return null;
                }
                currentParent = currentContainer;
                currentLevelItems = (matchingChild as PathItem)?.Items;
            }
            return currentContainer;
        }

        // Instance method (unlike CollapseAllRecursive) because it needs UpdateLayout() to force
        // WPF to realize each level's child containers before recursing into them - unlike collapse
        // (which only runs after the tree is already fully expanded, so every container already
        // exists), expand starts from a partially- or fully-collapsed tree, where a child
        // TreeViewItem's container may not exist yet until its parent's IsExpanded is actually
        // applied and laid out.
        private void ExpandAllRecursive(TreeViewItem treeViewItem)
        {
            treeViewItem.IsExpanded = true;
            this.UpdateLayout();
            foreach (var item in treeViewItem.Items)
            {
                if (treeViewItem.ItemContainerGenerator.ContainerFromItem(item) is TreeViewItem childItem)
                {
                    ExpandAllRecursive(childItem);
                }
            }
        }
        #endregion

        #region Collapse
        // "All" (see AllFilesPath) never collapses - it's the tree's permanent root, so "collapse
        // all" means collapse everything below it down to just its immediate (first-level) children,
        // not literally everything.
        public void CollapseAll()
        {
            this.DontInvoke = true;
            (TreeViewItem allContainer, List<Item> allChildren) = TryGetAllRootContainerAndChildren();
            if (allContainer != null)
            {
                allContainer.IsExpanded = true;
                bool allIsActive = this.SelectedPath == AllFilesPath;
                allContainer.IsSelected = allIsActive;
                if (allIsActive && this.FocusSelection)
                {
                    allContainer.Focus();
                }
                foreach (Item item in allChildren ?? [])
                {
                    if (allContainer.ItemContainerGenerator.ContainerFromItem(item) is TreeViewItem treeViewItem)
                    {
                        // After a full collapse, only first-level items remain visible - everything
                        // beneath is hidden regardless of its own IsSelected state. If the active item
                        // lives under this first-level item, mark THIS item (and only this one, not
                        // any of its now-hidden descendants) as selected, so the collapsed branch
                        // containing the active item still shows a highlight indicating where it is -
                        // mirroring what WPF's own TreeView.HandleSelectionAndCollapsed already does
                        // for a single manual collapse (moving selection to the collapsed ancestor),
                        // which CollapseAll used to undo by unconditionally clearing IsSelected on
                        // every node including this one.
                        bool isActivePathAncestorOrSelf = !allIsActive && !string.IsNullOrWhiteSpace(this.SelectedPath) &&
                            item is PathItem pathItem &&
                            (this.SelectedPath == pathItem.Path || this.SelectedPath.StartsWith(pathItem.Path + "\\", StringComparison.Ordinal));
                        CollapseAllRecursive(treeViewItem, isActivePathAncestorOrSelf);
                        if (isActivePathAncestorOrSelf && this.FocusSelection)
                        {
                            // Focusing this changes the highlight color to blue rather than shaded grey.
                            treeViewItem.Focus();
                        }
                    }
                }
            }
            this.DontInvoke = false;
        }

        // keepSelected is true only for the single top-level item (if any) that is itself the active
        // item or an ancestor of it; every descendant is always deselected regardless, since only one
        // item can be TreeView.SelectedItem at a time and descendants are hidden after a full collapse
        // anyway - letting a deeper match also claim IsSelected=true would silently steal the
        // selection away from the top-level item that's actually still visible.
        private static void CollapseAllRecursive(TreeViewItem treeViewItem, bool keepSelected)
        {
            treeViewItem.IsExpanded = false;
            treeViewItem.IsSelected = keepSelected;
            foreach (var item in treeViewItem.Items)
            {
                if (treeViewItem.ItemContainerGenerator.ContainerFromItem(item) is TreeViewItem childItem)
                {
                    CollapseAllRecursive(childItem, false);
                }
            }
        }
        #endregion

        #region UnselectAll
        public void UnselectAll()
        {
            this.DontInvoke = true;
            foreach (var item in this.Items)
            {
                UnselectAllRecursive((TreeViewItem)this.ItemContainerGenerator.ContainerFromItem(item));
            }
            this.DontInvoke = false;
        }

        // Unselect all items in the tree
        private static void UnselectAllRecursive(TreeViewItem treeViewItem)
        {
            if (treeViewItem == null) return;

            treeViewItem.IsSelected = false;

            foreach (var subItem in treeViewItem.Items)
            {
                UnselectAllRecursive((TreeViewItem)treeViewItem.ItemContainerGenerator.ContainerFromItem(subItem));
            }
        }
        #endregion
    }

    #region Item, PathItem, ItemProvider and ListItem classes
    internal class Item
    {
        public string Name { get; set; }
        public string Path { get; set; }
    }

    internal class PathItem : Item
    {
        public List<Item> Items { get; set; } = [];
    }

    // The ItemProvider creates a data structure based on a list of relative paths.
    // It assumes that the list is an ordered list of all path components, e.g.:
    //  a, a/b, a/b/c, a/b/d, c, c/d, etc 
    // It does this in a similar manner to recursively searching for folders in a folder system, 
    // i.e., for each top level folder, find the one that matches the first element in the path, 
    //       then recursively do that for that elements' child folders
    internal class ItemProvider
    {
        private List<string> RelativePaths { get; }
        internal ItemProvider(List<string> relativePaths)
        {
            this.RelativePaths = relativePaths;
        }

        internal List<Item> GetItems()
        {
            return GetItems(this.RelativePaths, "");
        }

        // Recursively search the list for the node that represents the path
        // null if there is no match
        internal static PathItem Search(List<Item> items, string path)
        {
            string head = Util.FilesFolders.GetRelativePathRootFolder(path);
            string tail = Util.FilesFolders.GetRelativePathSubFolder(path);
            foreach (Item item in items)
            {
                PathItem pathItem = (PathItem)item;
                if (pathItem.Name == head)
                {
                    return string.IsNullOrWhiteSpace(tail)
                        ? pathItem
                        : Search(pathItem.Items, tail);
                }
            }
            return null;
        }

        // Given a list of paths, return a hierarchical data structure representing the path elements as a tree
        private List<Item> GetItems(List<string> paths, string pathToHere)
        {
            List<ListItem> listItems = SplitIntoListsByRoot(paths);
            List<Item> items = [];
            foreach (ListItem listItem in listItems)
            {
                string newPathToHere = Path.Combine(pathToHere, listItem.PathHead);
                PathItem item = new()
                {
                    Name = listItem.PathHead,
                    Path = newPathToHere,
                    Items = GetItems(listItem.PathTails, newPathToHere)
                };
                items.Add(item);
            }

            return items;
        }

        // Given a list of paths, create multiple lists, each collecting paths with a common root
        // e.g a, a/b, a/b/c, a/b/d, c, c/d, will be compile into two lists:
        //     a, a/b, a/b/c, a/b/d
        //     c, c/d,
        private static List<ListItem> SplitIntoListsByRoot(List<string> paths)
        {
            List<ListItem> splitLists = [];
            ListItem commonRootPathList = new();
            string currentParent = string.Empty;
            foreach (string path in paths)
            {
                string parent = Util.FilesFolders.GetRelativePathRootFolder(path);
                if (string.IsNullOrEmpty(parent))
                {
                    continue;
                }

                if (currentParent != parent && false == string.IsNullOrEmpty(parent))
                {
                    currentParent = parent;
                    commonRootPathList = new()
                    {
                        PathHead = parent,
                        PathTails = [],
                    };
                    string tail = Util.FilesFolders.GetRelativePathSubFolder(path);
                    if (false == string.IsNullOrWhiteSpace(tail))
                    {
                        commonRootPathList.PathTails.Add(tail);
                    }
                    splitLists.Add(commonRootPathList);
                }
                else
                {
                    string tail = Util.FilesFolders.GetRelativePathSubFolder(path);
                    if (false == string.IsNullOrWhiteSpace(tail))
                    {
                        commonRootPathList.PathTails.Add(tail);
                    }
                }
            }
            return splitLists;
        }

        // A list item has a head, and all the children paths that comprise its tail e.g., 
        // PathHead = a, PathTails = b, b/c, b/d, etc

        public class ListItem
        {
            public string PathHead { get; set; }
            public List<string> PathTails { get; set; }
        }
        #endregion
    }
